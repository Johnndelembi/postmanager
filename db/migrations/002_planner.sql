CREATE TABLE IF NOT EXISTS user_settings (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  timezone TEXT NOT NULL DEFAULT 'Africa/Dar_es_Salaam',
  queue_times TEXT[] NOT NULL DEFAULT ARRAY['09:00', '18:00'],
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tiktok_accounts (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  open_id TEXT NOT NULL UNIQUE,
  username TEXT,
  access_token_ciphertext TEXT NOT NULL,
  refresh_token_ciphertext TEXT NOT NULL,
  access_expires_at TIMESTAMPTZ NOT NULL,
  refresh_expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL DEFAULT '',
  caption TEXT NOT NULL DEFAULT '',
  video_url TEXT,
  duration_seconds INTEGER CHECK (duration_seconds IS NULL OR duration_seconds > 0),
  privacy_level TEXT,
  allow_comment BOOLEAN NOT NULL DEFAULT false,
  allow_duet BOOLEAN NOT NULL DEFAULT false,
  allow_stitch BOOLEAN NOT NULL DEFAULT false,
  is_aigc BOOLEAN NOT NULL DEFAULT false,
  brand_organic_toggle BOOLEAN NOT NULL DEFAULT false,
  brand_content_toggle BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'queued', 'scheduled', 'publishing', 'published', 'failed')),
  scheduled_at TIMESTAMPTZ,
  approved_at TIMESTAMPTZ,
  published_at TIMESTAMPTZ,
  tiktok_publish_id TEXT,
  tiktok_post_id TEXT,
  view_count BIGINT,
  like_count BIGINT,
  comment_count BIGINT,
  share_count BIGINT,
  analytics_synced_at TIMESTAMPTZ,
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS posts_user_status_time ON posts(user_id, status, scheduled_at);
CREATE INDEX IF NOT EXISTS posts_due ON posts(scheduled_at) WHERE status IN ('queued', 'scheduled');
CREATE UNIQUE INDEX IF NOT EXISTS posts_user_reserved_time ON posts(user_id, scheduled_at)
  WHERE status IN ('queued', 'scheduled') AND scheduled_at IS NOT NULL;

CREATE TABLE IF NOT EXISTS post_metric_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  captured_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  view_count BIGINT NOT NULL,
  like_count BIGINT NOT NULL,
  comment_count BIGINT NOT NULL,
  share_count BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS post_metric_snapshots_post_time ON post_metric_snapshots(post_id, captured_at DESC);
