-- Phone OTP and application sessions use Unix epoch seconds in BIGINT columns.
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone TEXT NOT NULL UNIQUE,
  created_at BIGINT NOT NULL,
  last_activity_at BIGINT NOT NULL
);

CREATE TABLE otp_challenges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone TEXT NOT NULL,
  otp_hash TEXT NOT NULL,
  sent_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  used_at BIGINT
);
CREATE INDEX otp_challenges_phone_sent_idx ON otp_challenges (phone, sent_at DESC, id DESC);
CREATE INDEX otp_challenges_sent_idx ON otp_challenges (sent_at);

CREATE TABLE otp_ip_rate_limits (
  ip_hash TEXT NOT NULL,
  window_start BIGINT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  PRIMARY KEY (ip_hash, window_start)
);
CREATE INDEX otp_ip_rate_limits_window_idx ON otp_ip_rate_limits (window_start);
